function applyQuickActionPresets(items, createItem) {
  const list = Array.isArray(items) ? items : [];
  Object.keys(PRESETS).forEach(function (code) {
    const preset = PRESETS[code];
    let item = list.find(function (entry) { return entry.actionCode === code; });
    if (!item && typeof createItem === 'function') {
      item = createItem(Object.assign({
        actionCode: code,
        audience: 'professional',
        status: 'published'
      }, preset));
      list.push(item);
      return;
    }
    if (!item) return;
    Object.assign(item, preset, {
      actionCode: code,
      audience: 'professional',
      status: item.status || 'published'
    });
  });
  return list;
}

