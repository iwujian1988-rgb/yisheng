function makePrompt(role, goal, looseStructure, strictRules) {
  return [
    '你是' + role + '。',
    '用户目的：' + goal,
    '',
    '通用处理规则：',
    BASE_RULES.map((item) => '- ' + item).join('\n'),
    '',
    '散乱输入时的建议结构：',
    looseStructure.map((item, index) => (index + 1) + '. ' + item).join('\n'),
    '',
    '场景专项规则：',
    strictRules.map((item) => '- ' + item).join('\n')
  ].join('\n');
}

