const SHARED_EXPANSION_RULES = {
  allowed: [
    '把口语短句改写为语法完整、衔接自然的正式书面句',
    '按时间顺序、主题归属和模板章节重组已提供事实',
    '在不改变含义的前提下补足主语、谓语、时间连接词和规范标点',
    '把同一章节中的多个已知事实合并为连贯段落',
    '对已提供事实做不增加新结论的概括性摘要'
  ],
  forbidden: [
    '不得用重复表达、空话或同义改写机械凑字数',
    '不得为已提供的建议补写原文没有的理由、目的、预期收益、效果评价或医学解释',
    '不得补写源材料没有的症状、病史、检查、诊断、方案、药物、风险或结论',
    '不得把常见做法、医学常识或模板示例当作本次事实',
    '不得改变事实的主体、时间、否定、程度、不确定性或数值单位'
  ]
};

function blueprint(definition) {
  return Object.assign({
    version: 1,
    detailLevel: 'standard-rich',
    expansionRules: SHARED_EXPANSION_RULES,
    lengthPolicy: {
      principle: '篇幅随有效材料增加，不按固定字数编造内容。',
      targetExpansionRatio: '当材料是多个零散短句时，正文通常可达到有效源材料的1.4至2.2倍；这只是参考范围，不是必须凑够的字数。',
      minimumSourceChars: 60,
      minimumBodyChars: 80,
      minimumBodyToSourceRatio: 1.2,
      method: '只能通过完整句、时间线、章节组织、术语规范和必要摘要增加可读性，不得重复凑字；材料已规范或无法安全扩写时允许低于参考比例。'
    },
    outputRules: [
      '严格使用本蓝图的章节名称和顺序，仅输出有事实支撑的章节。',
      '叙述性章节优先写成连贯段落，不把每个字段机械列成一行。',
      '列表只用于模板本身要求逐项列举的内容。',
      '格式范式中的花括号是写作位置提示，绝不能原样输出。'
    ]
  }, definition || {});
}

