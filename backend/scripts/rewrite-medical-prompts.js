const PROMPT_TEMPLATE = (dept, structure, terms) => `你是${dept}病历书写助手。医生会提供一段简短接诊记录，请将其扩展整理为内容充实的专业病历。

格式结构：
${structure}

写作要求：
- 语言完全贴合临床病历书面语，正式严谨，语句流畅
- 将口语转为医学术语${terms ? '（如' + terms + '）' : ''}
- 医生提到的症状、查体、检查、诊断、用药，规范地写入对应段落
- 根据医生提到的诊断或主要症状，生成标准临床推理、诊疗思路和处理原则（如：脾虚→健脾益气，骨折→固定+复查X线）
- 医生未提及但该诊断常见的伴随表现，用概括性描述（如"伴纳差、便溏"），用"（需确认）"标注
- 不编造医生未提及的具体细节：不确定的部位写"患处"而非编造具体位置，不确定的具体操作写"常规换药处理"而非编造步骤，不确定的具体数值不编造
- 不要大片留白或整段写"未提供"，每个段落至少应有标准临床描述或推理
- 常规复查、随访建议和注意事项结合科室常规生成`;

const filePath = path.resolve(__dirname, '..', 'data', 'store.json');

function main() {
  var store;
  if (fs.existsSync(filePath)) {
    store = JSON.parse(fs.readFileSync(filePath, 'utf8'));
  } else {
    console.error('store.json not found at', filePath);
    process.exit(1);
  }

  var updated = 0;
  store.templates.forEach(function(tpl) {
    var cfg = DEPARTMENT_CONFIG[tpl.templateCode];
    if (!cfg) return;
    tpl.variableDefs = makeField(tpl.templateCode);
    tpl.promptContent = PROMPT_TEMPLATE(cfg.dept, cfg.structure, cfg.terms);
    tpl.outputStructure = cfg.structure.split('\n').map(function(s) {
      return s.replace(/^\d+\.\s*/, '').split('：')[0].split('(')[0].trim();
    }).filter(Boolean);
    updated++;
  });

  fs.writeFileSync(filePath, JSON.stringify(store, null, 2), 'utf8');
  console.log('Updated ' + updated + ' medical templates');
  console.log('Templates changed:');
  Object.keys(DEPARTMENT_CONFIG).forEach(function(code) {
    console.log('  ' + code);
  });
}

main();
